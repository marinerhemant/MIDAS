def test_the_220_m1_branch_is_the_slip_class_the_footnote_omits():
    """None of the footnote's four (b,l) pairs produces the 0.64->0.37 220 branch."""
    ratio, ai = 0.5, 0.5
    printed = TABLE2[(0.5, 220, 1, 1)][0]                    # 0.6406
    for j, (b, l) in FOOTNOTE_BL.items():
        got = edge_C(ai, ratio, (2, 2, 0), b, _n_from_bl(b, l), line=l)
        assert abs(got - printed) > 1e-2, (
            f"footnote j={j} reproduces the branch after all ({got:.4f}); "
            "the omitted-class explanation is then unnecessary")
    got = edge_C(ai, ratio, (2, 2, 0), OMITTED_220["burgers"], OMITTED_220["slip_normal"])
    assert abs(got - printed) <= TOL


def test_the_omitted_220_class_has_b_parallel_to_g():
    """Why the footnote plausibly dropped it: b || g is the degenerate-looking case."""
    b = np.array(OMITTED_220["burgers"], dtype=float)
    g = np.array([2, 2, 0], dtype=float)
    assert abs(abs(b @ g) / (np.linalg.norm(b) * np.linalg.norm(g)) - 1.0) < 1e-12
    n = np.array(OMITTED_220["slip_normal"], dtype=float)
    assert abs(b @ n) < 1e-12                                # still a valid slip system


def test_the_111_rows_are_interchanged_at_c12_over_c44_equals_3():
    """As printed the rows are wrong by 0.06-0.09; swapped, all 14 land inside 5e-5."""
    as_printed, swapped = [], []
    for (m, j) in ((2, 1), (1, 3)):
        b, n = _expected_geometry(111, m, j)
        other = (1, 3) if (m, j) == (2, 1) else (2, 1)
        for ai in AI:
            got = edge_C(ai, 3.0, (1, 1, 1), b, n)
            as_printed.append(abs(got - TABLE2[(3.0, 111, m, j)][AI.index(ai)]))
            swapped.append(abs(got - TABLE2[(3.0, 111, *other)][AI.index(ai)]))
    as_printed, swapped = np.array(as_printed), np.array(swapped)
    assert len(swapped) == 14
    assert swapped.max() <= TOL, f"swap does not fix it: max {swapped.max():.3e}"
    assert as_printed.min() > 0.05, "as printed it is not actually wrong; swap unmotivated"


def test_the_swap_is_not_needed_at_the_other_three_ratios():
    """If the swap were our bug rather than the paper's, it would be needed everywhere."""
    for ratio in (0.5, 1.0, 2.0):
        for (m, j) in ((2, 1), (1, 3)):
            b, n = _expected_geometry(111, m, j)
            devs = [abs(edge_C(ai, ratio, (1, 1, 1), b, n)
                        - TABLE2[(ratio, 111, m, j)][AI.index(ai)])
                    for ai in AI if (ratio, 111, m, j, ai) not in KNOWN_BAD]
            assert max(devs) <= TOL, f"c12/c44={ratio} (m,j)=({m},{j}) needs a swap too"


