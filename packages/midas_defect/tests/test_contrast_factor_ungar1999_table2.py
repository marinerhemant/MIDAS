def stiffness(Ai, ratio, c44=1.0):
    """C is homogeneous of degree 0 in c_ij, so (Ai, c12/c44) fixes it up to scale.

    Paper p.994: Ai = 2*c44/(c11 - c12), and "the values of C depend only on the ratios
    of the elastic constants".
    """
    c12 = ratio * c44
    return cubic_stiffness(c12 + 2.0 * c44 / Ai, c12, c44)


def edge_C(Ai, ratio, hkl, burgers, slip_normal, line=None, **kw):
    if line is None:
        line = list(np.cross(slip_normal, burgers))
    return float(single_contrast_factor(stiffness(Ai, ratio), burgers=burgers,
                                        slip_normal=slip_normal, line=line,
                                        g=list(hkl), **kw))


def _n_from_bl(b, l):
    n = np.cross(b, l)
    g = np.gcd.reduce(np.abs(n).astype(int))
    return list((n // g).astype(int))


