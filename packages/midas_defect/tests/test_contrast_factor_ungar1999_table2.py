def _expected_geometry(hkl, m, j):
    """Which slip class the printed row actually corresponds to, and the swap fix."""
    if hkl == 220 and m == 1 and j == 1:
        return OMITTED_220["burgers"], OMITTED_220["slip_normal"]      # footnote omits it
    b, l = FOOTNOTE_BL[j]
    return b, _n_from_bl(b, l)


def _printed_key(ratio, hkl, m, j):
    """At c12/c44 = 3, hkl 111, the m=2 and m=1,j=3 rows are interchanged in print."""
    if ratio == 3.0 and hkl == 111:
        if (m, j) == (2, 1):
            return (1, 3)
        if (m, j) == (1, 3):
            return (2, 1)
    return (m, j)


ALL_ENTRIES = [(r, hkl, m, j, ai)
               for (r, hkl, m, j), vals in sorted(TABLE2.items())
               for ai in AI]


def test_the_reference_table_is_the_full_252_entry_grid():
    """Guards the claim's scope: Table 2 is 252 individual values, not 56 averages."""
    assert len(TABLE2) == 36
    assert sum(len(v) for v in TABLE2.values()) == 252
    assert len(ALL_ENTRIES) == 252
    for hkl, n in ((200, 56), (220, 112), (111, 84)):
        assert sum(len(v) for (r, h, m, j), v in TABLE2.items() if h == hkl) == n


@pytest.mark.parametrize("ratio,hkl,m,j,ai", ALL_ENTRIES,
                         ids=lambda x: str(x) if not isinstance(x, tuple) else None)
def test_table2_entry(ratio, hkl, m, j, ai):
    """Every printed entry, against the code, at the table's own 4-dp rounding."""
    src_m, src_j = _printed_key(ratio, hkl, m, j)
    printed = TABLE2[(ratio, hkl, src_m, src_j)][AI.index(ai)]
    b, n = _expected_geometry(hkl, m, j)
    got = edge_C(ai, ratio, (hkl // 100, (hkl // 10) % 10, hkl % 10), b, n)
    dev = abs(got - printed)
    key = (ratio, hkl, m, j, ai)
    if key in KNOWN_BAD:
        expected_dev, why = KNOWN_BAD[key]
        assert dev == pytest.approx(expected_dev, rel=0.05), (
            f"a KNOWN_BAD entry moved: {key} now deviates {dev:.3e}, was {expected_dev:.3e}. "
            f"Recorded reason: {why}. Either the code changed or the reason is wrong.")
        pytest.xfail(f"published table entry is wrong: {why} (dev {dev:.2e})")
    assert dev <= TOL, f"{key}: printed {printed:.4f}, code {got:.6f}, dev {dev:.3e}"


def test_the_grid_is_overwhelmingly_clean():
    """Aggregate: at most the seven documented exceptions may miss."""
    n_bad = 0
    for ratio, hkl, m, j, ai in ALL_ENTRIES:
        src_m, src_j = _printed_key(ratio, hkl, m, j)
        printed = TABLE2[(ratio, hkl, src_m, src_j)][AI.index(ai)]
        b, n = _expected_geometry(hkl, m, j)
        got = edge_C(ai, ratio, (hkl // 100, (hkl // 10) % 10, hkl % 10), b, n)
        if abs(got - printed) > TOL:
            n_bad += 1
    assert n_bad == len(KNOWN_BAD) == 7, f"{n_bad} entries miss, expected exactly 7"


def test_the_200_block_is_clean_but_for_one_last_digit():
    """The 200 block alone -- the subset most often quoted."""
    devs = []
    for (ratio, hkl, m, j), vals in TABLE2.items():
        if hkl != 200:
            continue
        b, n = _expected_geometry(hkl, m, j)
        for ai, printed in zip(AI, vals):
            devs.append(abs(edge_C(ai, ratio, (2, 0, 0), b, n) - printed))
    devs = np.array(devs)
    assert len(devs) == 56
    assert (devs > TOL).sum() == 1          # the 0.4778 / 0.477897 last digit
    assert devs.max() < 1e-4
    assert np.median(devs) < 3.5e-5


