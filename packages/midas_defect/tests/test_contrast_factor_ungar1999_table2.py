def test_slip_system_multiplicities_match_the_printed_m_column():
    """200 -> 8:4, 220 -> 4:4:2:2, 111 -> 6:3:3 over the 12 fcc systems."""
    C6 = stiffness(2.0, 1.0)
    for hkl, expected in (((2, 0, 0), [8, 4]),
                          ((2, 2, 0), [4, 4, 2, 2]),
                          ((1, 1, 1), [6, 3, 3])):
        vals = []
        for n, b in fcc_slip_systems():
            vals.append(round(float(single_contrast_factor(
                C6, burgers=list(b), slip_normal=list(n),
                line=list(np.cross(n, b)), g=list(hkl))), 9))
        counts = sorted((vals.count(v) for v in set(vals)), reverse=True)
        assert counts == expected, f"{hkl}: degeneracy {counts}, expected {expected}"
        assert sum(counts) == 12


def test_the_footnote_bl_pairs_are_mutually_orthogonal_slip_systems():
    """b . n = l . n = b . l = 0 for each printed (b, l); a sanity check on the key."""
    for j, (b, l) in FOOTNOTE_BL.items():
        n = _n_from_bl(b, l)
        assert abs(np.dot(b, n)) < 1e-12, f"j={j}: b not in the slip plane"
        assert abs(np.dot(l, n)) < 1e-12, f"j={j}: l not in the slip plane"
        assert abs(np.dot(b, l)) < 1e-12, f"j={j}: edge requires l perpendicular to b"


