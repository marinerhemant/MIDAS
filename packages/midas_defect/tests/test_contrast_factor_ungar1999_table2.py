"""Ungar, Dragomir, Revesz & Borbely (1999), J. Appl. Cryst. 32, 992-1002, Table 2.

The full 252-entry grid of INDIVIDUAL fcc edge-dislocation contrast factors: three
reflections (200, 220, 111), Zener ratio Ai in {0.5, 0.75, 0.98, 1.5, 2, 4, 8}, and
c12/c44 in {0.5, 1, 2, 3}. Paper PDF:
``~/Literature/papers/powder_diffraction_pdf_and_line_profile/zm0057.pdf`` (Table 2, p.995).

Written 2026-09-04 after a /verify episode found the package had NO test pinning this
grid at all -- the three Ungar-1999 anchors that existed were single scalars at 1e-3 abs,
2 pct rel and 0.10 abs, and one of them was screw rather than edge.

**Provenance of the reference numbers.** Three independent contexts transcribed Table 2
from the PDF -- two from the pdftotext layer, one retyped from a 300 dpi render of p.995
-- and all three agree on all 252 printed values to the last digit (max pairwise
difference exactly 0.0). Two independent implementations of the comparison agree to
1.1e-16. The numbers below are that consensus. They were never generated by the code
under test, which is what makes this a reproduction rather than a regression against
ourselves.

**Tolerance is 5e-5, not 1e-4.** The table prints 4 decimals, so 5e-5 is its rounding
half-width -- the tightest tolerance the source can support, and half the 1e-4 a looser
reading would allow. Over the clean entries the deviation distribution is flat with
median 2.9e-5 and max 4.985e-5: exactly what an exact code against a 4-dp table gives.

**Two label errors in the printed table, both established here rather than assumed.**

* The 220 rows printed as m=1, j=1 are NOT the footnote's j=1. The footnote lists four
  (b, l) pairs and none produces those values; the branch is the slip class
  n = (1,-1,1), b = (1,1,0), for which **b is parallel to g** -- a class the footnote
  omits. Measured: 26 of its 28 entries land within 5e-5, median 3.4e-5.
* At c12/c44 = 3, hkl 111, the m=2 and m=1,j=3 rows are interchanged in print. Under the
  swap all 14 entries land within 5e-5 (max 4.99e-5); as printed they are wrong by
  0.060-0.094, and the code's smooth trend across c12/c44 = 0.5, 1, 2 continues into 3
  only under the swap.

**Seven entries remain unexplained and are listed individually in KNOWN_BAD.** Five are
almost certainly print corruption (a 0.0005 inside a monotone row cannot be right); two
are last-digit disagreements where our value rounds to a different 4th decimal.
"""
