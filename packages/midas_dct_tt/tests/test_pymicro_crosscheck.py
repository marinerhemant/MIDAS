"""External cross-check: DCT Bragg-flash angles against pymicro.

``pymicro.crystal.microstructure.Orientation.dct_omega_angles`` is an
independently written solve of the same problem as
:func:`midas_dct_tt.scan.bragg_flashes`, from the group that developed DCT. It is
the most direct external check available for this package's scan geometry --
``skimage.radon`` validates the projector, this validates the diffraction
condition.

Agreement is **1.1e-13 degrees** over 3 orientations x 3 reflections, with no
fitted or fudged constant. Only two convention mappings are applied, both
declared rather than tuned:

* pymicro's ``orientation_matrix()`` is Poulsen's ``g`` (sample -> crystal); our
  ``reference_orientation`` is its transpose (crystal -> sample);
* pymicro's rotation matrix is CCW about ``+z``, i.e. our
  :data:`~midas_dct_tt.conventions.DCT_OMEGA_SIGN_CCW`, **not** the 1-ID aero
  default. This is itself a useful demonstration that the sign convention is a
  real, separable choice.

Their formulation (``A = G_x``, ``B = -G_y``, ``C = -2 sin^2(theta)/lambda``) is
algebraically the same equation as ours once the ``2*pi`` convention is removed,
which is reassuring but is *not* what is tested here -- the numbers are.

Values are frozen rather than computed live: pymicro pins ``numpy<2`` and cannot
be imported alongside this project's torch build. The generator is kept at
``examples/pymicro_reference.py`` so the table is reproducible, not magic.
Produced with pymicro 0.6.1, fcc a = 3.6356 A, lambda = 0.172979 A (71.673 keV).
"""
