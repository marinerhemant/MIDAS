def _g_sample(entry):
    """Sample-frame scattering vector for a reference entry, our conventions."""
    B = reciprocal_basis(torch.tensor(LATTICE, dtype=DT))
    OM0 = torch.tensor(entry["g_crystal_to_sample"], dtype=DT)
    return OM0 @ (B @ torch.tensor(entry["hkl"], dtype=DT))


@pytest.mark.unit
@pytest.mark.parametrize("entry", REFERENCE, ids=lambda e: f"{e['euler']}-{e['hkl']}")
def test_flash_angles_match_pymicro(entry):
    """Our closed-form solve vs pymicro's.

    Measured max over the 18 comparisons: 2.9e-11 deg (median 6.6e-12).
    The reference above is stored at FULL double precision. It used to be
    written through round(w, 10), which quantised it at 1e-10 deg -- so the
    previously claimed 1.1e-13 deg agreement was three orders below what the
    reference could even express, and could never have been measured. Removing
    the rounding moved the worst case only from 4.9e-11 to 2.9e-11, so the
    residual is a real difference between the two implementations.
    """
    flashes = bragg_flashes(_g_sample(entry), LAMBDA_A, omega_sign=DCT_OMEGA_SIGN_CCW)
    assert len(flashes) == 2
    mine = sorted(f.omega_deg for f in flashes)
    for got, want in zip(mine, entry["omegas"]):
        assert abs(got - want) < 1e-10


@pytest.mark.unit
def test_reference_table_is_not_degenerate():
    """Guard the guard: distinct orientations must give distinct angles.

    A table of identical values would let a broken solve pass everything above.
    """
    all_omegas = [tuple(e["omegas"]) for e in REFERENCE]
    assert len(set(all_omegas)) == len(all_omegas)
    assert len(REFERENCE) == 9


@pytest.mark.unit
def test_aero_sign_disagrees_with_pymicro_on_an_asymmetric_orientation():
    """The stage sign is a real choice, not a free parameter.

    With an asymmetric orientation the 1-ID aero (CW) default must NOT reproduce
    pymicro's CCW angles. If it did, the sign would be doing nothing.
    """
    entry = next(e for e in REFERENCE if e["euler"] == [35.0, 27.0, 14.0]
                 and tuple(e["hkl"]) == (1, 1, 1))
    cw = sorted(f.omega_deg for f in bragg_flashes(_g_sample(entry), LAMBDA_A))
    assert max(abs(a - b) for a, b in zip(cw, entry["omegas"])) > 1.0


@pytest.mark.unit
def test_some_orientations_are_blind_to_the_stage_sign():
    """...and some are not, which is exactly why the sign hazard is dangerous.

    For euler [0,0,0] (200) the two flashes sit at 92.727 and 267.273 deg --
    symmetric about 180 -- so negating omega maps the pair onto *itself* and the
    CW and CCW conventions give identical angles (agreement here: 2e-11 deg).

    A sign check performed on such a configuration passes regardless of the
    truth. That is the mechanism behind "a wrong omega sign mirrors the
    reconstruction undetectably": whole classes of reflection are sign-blind, so
    the error must be excluded by knowing the hardware, not by fitting the data.
    """
    entry = next(e for e in REFERENCE if e["euler"] == [0.0, 0.0, 0.0]
                 and tuple(e["hkl"]) == (2, 0, 0))
    cw = sorted(f.omega_deg for f in bragg_flashes(_g_sample(entry), LAMBDA_A))
    ccw = sorted(f.omega_deg for f in
                 bragg_flashes(_g_sample(entry), LAMBDA_A, omega_sign=DCT_OMEGA_SIGN_CCW))
    assert max(abs(a - b) for a, b in zip(cw, ccw)) < 1e-9
    assert abs((cw[0] + cw[1]) - 360.0) < 1e-9        # the symmetry that hides it
